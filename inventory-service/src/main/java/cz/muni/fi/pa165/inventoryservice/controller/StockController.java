package cz.muni.fi.pa165.inventoryservice.controller;

import cz.muni.fi.pa165.commonservice.openapi.SwaggerConstants;
import cz.muni.fi.pa165.commonservice.rest.exceptionhandling.ApiError;
import cz.muni.fi.pa165.inventoryservice.api.StockDetailedViewDto;
import cz.muni.fi.pa165.inventoryservice.api.StockQuantityChangeDto;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.security.SecurityRequirement;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import cz.muni.fi.pa165.inventoryservice.facade.StockFacade;

import java.util.List;
import java.util.UUID;

@RestController
@RequestMapping("/stocks")
@Tag(name = "Stocks",
    description = "Endpoints for managing wine stock quantities — create, read, update, delete entries, "
        + "as well as add or remove specific bottle counts.")
public class StockController {

    private final StockFacade stockFacade;

    @Autowired
    public StockController(StockFacade stockFacade) {
        this.stockFacade = stockFacade;
    }

    @PostMapping
    @Operation(
        summary = "Create a stock entry",
        description = "Creates a new stock entry for a wine identified by its wineId. "
            + "The wineId is unique per stock — repeated creation for the same wine is not allowed.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.WRITE_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.CREATED, description = "Stock created",
            content = @Content(schema = @Schema(implementation = StockDetailedViewDto.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.BAD_REQUEST, description = SwaggerConstants.ResponseDescriptions.BAD_REQUEST,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<StockDetailedViewDto> create(
        @Valid
        @io.swagger.v3.oas.annotations.parameters.RequestBody(
            description = "Stock entry to create. Identifier is generated by the service.",
            required = true,
            content = @Content(schema = @Schema(implementation = StockDetailedViewDto.class))
        )
        @RequestBody StockDetailedViewDto stock
    ) {
        StockDetailedViewDto created = stockFacade.create(stock);
        return ResponseEntity.status(HttpStatus.CREATED).body(created);
    }

    @GetMapping("/{id}")
    @Operation(
        summary = "Get a stock by id",
        description = "Returns one stock entry by its unique identifier.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.READ_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.OK, description = "Stock found",
            content = @Content(schema = @Schema(implementation = StockDetailedViewDto.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NOT_FOUND, description = SwaggerConstants.ResponseDescriptions.NOT_FOUND,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<StockDetailedViewDto> findById(
        @Parameter(description = "Stock identifier", example = "11111111-1111-1111-1111-111111111111")
        @PathVariable UUID id
    ) {
        StockDetailedViewDto stock = stockFacade.findById(id);
        if (stock == null) {
            return ResponseEntity.notFound().build();
        }
        return ResponseEntity.ok(stock);
    }

    @GetMapping
    @Operation(
        summary = "List all stocks",
        description = "Returns all stock entries currently registered in the inventory service.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.READ_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.OK, description = "Stocks returned",
            content = @Content(array = @io.swagger.v3.oas.annotations.media.ArraySchema(schema = @Schema(implementation = StockDetailedViewDto.class)))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<List<StockDetailedViewDto>> findAll() {
        return ResponseEntity.ok(stockFacade.findAll());
    }

    @GetMapping("/wine/{wineId}")
    @Operation(
        summary = "Get a stock by wine id",
        description = "Returns the stock entry associated with the given wine identifier.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.READ_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.OK, description = "Stock found",
            content = @Content(schema = @Schema(implementation = StockDetailedViewDto.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NOT_FOUND, description = "Stock not found for the given wine",
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<StockDetailedViewDto> findByWine(
        @Parameter(description = "Wine identifier", example = "22222222-2222-2222-2222-222222222222")
        @PathVariable UUID wineId
    ) {
        StockDetailedViewDto stock = stockFacade.findByWine(wineId);
        if (stock == null) {
            return ResponseEntity.notFound().build();
        }
        return ResponseEntity.ok(stock);
    }

    @PostMapping("/{id}/add")
    @Operation(
        summary = "Add quantity to a stock",
        description = "Increases the stock quantity by the value supplied in the request body. "
            + "Quantity must be positive.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.WRITE_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.OK, description = "Stock quantity updated",
            content = @Content(schema = @Schema(implementation = StockDetailedViewDto.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.BAD_REQUEST, description = SwaggerConstants.ResponseDescriptions.BAD_REQUEST,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NOT_FOUND, description = SwaggerConstants.ResponseDescriptions.NOT_FOUND,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<StockDetailedViewDto> addToStock(
        @Parameter(description = "Stock identifier", example = "11111111-1111-1111-1111-111111111111")
        @PathVariable UUID id,
        @Valid
        @io.swagger.v3.oas.annotations.parameters.RequestBody(
            description = "Positive quantity to add to the existing stock.",
            required = true,
            content = @Content(schema = @Schema(implementation = StockQuantityChangeDto.class))
        )
        @RequestBody StockQuantityChangeDto change
    ) {
        StockDetailedViewDto updated = stockFacade.addToStock(id, change.getQuantity());
        return ResponseEntity.ok(updated);
    }

    @PostMapping("/{id}/remove")
    @Operation(
        summary = "Remove quantity from a stock",
        description = "Decreases the stock quantity by the value supplied in the request body. "
            + "Quantity must be positive and cannot exceed currently available bottles.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.WRITE_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.OK, description = "Stock quantity updated",
            content = @Content(schema = @Schema(implementation = StockDetailedViewDto.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.BAD_REQUEST, description = "Invalid quantity or insufficient stock",
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NOT_FOUND, description = SwaggerConstants.ResponseDescriptions.NOT_FOUND,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<StockDetailedViewDto> removeFromStock(
        @Parameter(description = "Stock identifier", example = "11111111-1111-1111-1111-111111111111")
        @PathVariable UUID id,
        @Valid
        @io.swagger.v3.oas.annotations.parameters.RequestBody(
            description = "Positive quantity to remove. Cannot exceed currently available bottles.",
            required = true,
            content = @Content(schema = @Schema(implementation = StockQuantityChangeDto.class))
        )
        @RequestBody StockQuantityChangeDto change
    ) {
        StockDetailedViewDto updated = stockFacade.removeFromStock(id, change.getQuantity());
        return ResponseEntity.ok(updated);
    }

    @PutMapping("/{id}")
    @Operation(
        summary = "Update a stock",
        description = "Replaces an existing stock entry identified by id with the supplied payload.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.WRITE_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.OK, description = "Stock updated",
            content = @Content(schema = @Schema(implementation = StockDetailedViewDto.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.BAD_REQUEST, description = SwaggerConstants.ResponseDescriptions.BAD_REQUEST,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NOT_FOUND, description = SwaggerConstants.ResponseDescriptions.NOT_FOUND,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<StockDetailedViewDto> update(
        @Parameter(description = "Stock identifier", example = "11111111-1111-1111-1111-111111111111")
        @PathVariable UUID id,
        @Valid
        @io.swagger.v3.oas.annotations.parameters.RequestBody(
            description = "Stock entry data to apply.",
            required = true,
            content = @Content(schema = @Schema(implementation = StockDetailedViewDto.class))
        )
        @RequestBody StockDetailedViewDto stock
    ) {
        stock.setId(id);
        StockDetailedViewDto updated = stockFacade.update(stock);
        return ResponseEntity.ok(updated);
    }

    @DeleteMapping("/{id}")
    @Operation(
        summary = "Delete a stock",
        description = "Removes a stock entry from the inventory service.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.WRITE_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NO_CONTENT, description = "Stock deleted"),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NOT_FOUND, description = SwaggerConstants.ResponseDescriptions.NOT_FOUND,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<Void> delete(
        @Parameter(description = "Stock identifier", example = "11111111-1111-1111-1111-111111111111")
        @PathVariable UUID id
    ) {
        stockFacade.delete(id);
        return ResponseEntity.noContent().build();
    }

}
