package cz.muni.fi.pa165.inventoryservice.controller;

import cz.muni.fi.pa165.commonservice.openapi.SwaggerConstants;
import cz.muni.fi.pa165.commonservice.rest.exceptionhandling.ApiError;
import cz.muni.fi.pa165.inventoryservice.api.ReservationBasicViewDto;
import cz.muni.fi.pa165.inventoryservice.api.ReservationDetailedViewDto;
import cz.muni.fi.pa165.inventoryservice.facade.ReservationFacade;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.ArraySchema;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.security.SecurityRequirement;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.format.annotation.DateTimeFormat;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.time.LocalDate;
import java.util.List;
import java.util.UUID;

@RestController
@RequestMapping("/reservations")
@Tag(name = "Reservations",
    description = "Endpoints for managing customer reservations of wine bottles tracked by the inventory service.")
public class ReservationController {
    private final ReservationFacade reservationFacade;

    @Autowired
    public ReservationController(ReservationFacade reservationFacade) {
        this.reservationFacade = reservationFacade;
    }

    @PostMapping
    @Operation(
        summary = "Create a reservation",
        description = "Creates a reservation of a given wine quantity for a customer.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.WRITE_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.CREATED, description = "Reservation created",
            content = @Content(schema = @Schema(implementation = ReservationDetailedViewDto.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.BAD_REQUEST, description = SwaggerConstants.ResponseDescriptions.BAD_REQUEST,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<ReservationDetailedViewDto> create(
        @Valid
        @io.swagger.v3.oas.annotations.parameters.RequestBody(
            description = "Reservation to create. Identifier is generated by the service.",
            required = true,
            content = @Content(schema = @Schema(implementation = ReservationDetailedViewDto.class))
        )
        @RequestBody ReservationDetailedViewDto reservation
    ) {
        ReservationDetailedViewDto created = reservationFacade.create(reservation);
        return ResponseEntity.status(HttpStatus.CREATED).body(created);
    }

    @GetMapping("/{id}")
    @Operation(
        summary = "Get a reservation by id",
        description = "Returns a single reservation with customer and wine references.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.READ_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.OK, description = "Reservation found",
            content = @Content(schema = @Schema(implementation = ReservationDetailedViewDto.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NOT_FOUND, description = SwaggerConstants.ResponseDescriptions.NOT_FOUND,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<ReservationDetailedViewDto> findById(
        @Parameter(description = "Reservation identifier", example = "33333333-3333-3333-3333-333333333333")
        @PathVariable UUID id
    ) {
        ReservationDetailedViewDto reservation = reservationFacade.findById(id);
        if (reservation == null) {
            return ResponseEntity.notFound().build();
        }
        return ResponseEntity.ok(reservation);
    }

    @GetMapping
    @Operation(
        summary = "List all reservations",
        description = "Returns all reservations currently registered in the inventory service.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.READ_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.OK, description = "Reservations returned",
            content = @Content(array = @ArraySchema(schema = @Schema(implementation = ReservationBasicViewDto.class)))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<List<ReservationBasicViewDto>> findAll() {
        return ResponseEntity.ok(reservationFacade.findAll());
    }

    @GetMapping("/filter")
    @Operation(
        summary = "Filter reservations",
        description = "Returns reservations filtered by customer, wine and creation date range. "
            + "All parameters are optional and combined with logical AND.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.READ_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.OK, description = "Reservations returned",
            content = @Content(array = @ArraySchema(schema = @Schema(implementation = ReservationBasicViewDto.class)))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.BAD_REQUEST, description = "Invalid filter parameters (malformed UUID or date)",
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<List<ReservationBasicViewDto>> filter(
        @Parameter(description = "Filter by customer identifier", example = "44444444-4444-4444-4444-444444444444")
        @RequestParam(required = false) UUID customerId,
        @Parameter(description = "Filter by wine identifier", example = "22222222-2222-2222-2222-222222222222")
        @RequestParam(required = false) UUID wineId,
        @Parameter(description = "Return reservations created on or after this ISO date", example = "2026-01-01")
        @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate createdAfter,
        @Parameter(description = "Return reservations created on or before this ISO date", example = "2026-12-31")
        @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate createdBefore
    ) {
        return ResponseEntity.ok(reservationFacade.filter(customerId, wineId, createdAfter, createdBefore));
    }

    @PutMapping("/{id}")
    @Operation(
        summary = "Update a reservation",
        description = "Replaces an existing reservation identified by id with the supplied payload.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.WRITE_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.OK, description = "Reservation updated",
            content = @Content(schema = @Schema(implementation = ReservationDetailedViewDto.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.BAD_REQUEST, description = SwaggerConstants.ResponseDescriptions.BAD_REQUEST,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NOT_FOUND, description = SwaggerConstants.ResponseDescriptions.NOT_FOUND,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<ReservationDetailedViewDto> update(
        @Parameter(description = "Reservation identifier", example = "33333333-3333-3333-3333-333333333333")
        @PathVariable UUID id,
        @Valid
        @io.swagger.v3.oas.annotations.parameters.RequestBody(
            description = "Reservation data to apply.",
            required = true,
            content = @Content(schema = @Schema(implementation = ReservationDetailedViewDto.class))
        )
        @RequestBody ReservationDetailedViewDto reservation
    ) {
        reservation.setId(id);
        ReservationDetailedViewDto updated = reservationFacade.update(reservation);
        return ResponseEntity.ok(updated);
    }

    @DeleteMapping("/{id}")
    @Operation(
        summary = "Delete a reservation",
        description = "Removes a reservation from the inventory service.",
        security = @SecurityRequirement(name = SwaggerConstants.SECURITY_SCHEME_NAME, scopes = SwaggerConstants.WRITE_SCOPE)
    )
    @ApiResponses({
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NO_CONTENT, description = "Reservation deleted"),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.UNAUTHORIZED, description = SwaggerConstants.ResponseDescriptions.UNAUTHORIZED,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.FORBIDDEN, description = SwaggerConstants.ResponseDescriptions.FORBIDDEN,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.NOT_FOUND, description = SwaggerConstants.ResponseDescriptions.NOT_FOUND,
            content = @Content(schema = @Schema(implementation = ApiError.class))),
        @ApiResponse(responseCode = SwaggerConstants.ResponseCodes.INTERNAL_ERROR, description = SwaggerConstants.ResponseDescriptions.INTERNAL_ERROR,
            content = @Content(schema = @Schema(implementation = ApiError.class)))
    })
    public ResponseEntity<Void> delete(
        @Parameter(description = "Reservation identifier", example = "33333333-3333-3333-3333-333333333333")
        @PathVariable UUID id
    ) {
        reservationFacade.delete(id);
        return ResponseEntity.noContent().build();
    }
}
